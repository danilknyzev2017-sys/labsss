"""Вместо временного признака здесь полезнее оставить все содержательные признаки и отдельно закодировать категориальные колонки.

## Preprocessing

Подготовим данные: создадим бинарную цель Class, закодируем категориальные признаки и стандартизируем числовые.
"""

transactionData = df.copy()
transactionData = pd.get_dummies(transactionData, columns=['cut', 'color', 'clarity'], drop_first=True)
transactionData = transactionData.drop(['price'], axis=1)

"""Стандартизируем все числовые признаки, кроме Class.

"""

feature_cols = [col for col in transactionData.columns if col != 'Class']
transactionData[feature_cols] = StandardScaler().fit_transform(transactionData[feature_cols])

"""### Разделите набор данных на наборы обучающих и тестовых данных.

Разделим данные на обучение = 80% и тест = 20%. В обучающем наборе будут только обычные бриллианты, а в тестовом — и обычные, и дорогие.

"""

X_train, X_test = train_test_split(
    transactionData, test_size=0.2, random_state=RANDOM_SEED, stratify=transactionData['Class']
)
X_train = X_train[X_train.Class == 0]
X_train = X_train.drop(['Class'], axis=1)
y_test = X_test['Class']
X_test = X_test.drop(['Class'], axis=1)
input_dim = X_train.shape[1]
encoding_dim = max(4, input_dim // 2)
bottleneck_dim = max(2, input_dim // 4)
X_train = X_train.values.astype(np.float64)
X_test = X_test.values.astype(np.float64)
y_test = y_test.values
print('input_dim =', input_dim)
print('test size =', y_test.size)

"""## Model
Построим автоэнкодер, где размер входа теперь вычисляется автоматически по числу признаков после кодирования категориальных столбцов.

"""

class Autoencoder(nn.Module):
    def __init__(self, input_dim, encoding_dim, bottleneck_dim):
        super(Autoencoder, self).__init__()
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, encoding_dim),
            nn.Tanh(),
            nn.Linear(encoding_dim, bottleneck_dim),
            nn.LeakyReLU(),
        )
        self.decoder = nn.Sequential(
            nn.Linear(bottleneck_dim, bottleneck_dim),
            nn.Tanh(),
            nn.Linear(bottleneck_dim, input_dim),
            nn.LeakyReLU(),
        )
    def forward(self, x):
        x = self.encoder(x)
        x = self.decoder(x)
        return x

model = Autoencoder(input_dim, encoding_dim, bottleneck_dim).double()

num_epochs = 100
minibatch_size = 32
learning_rate = 1e-3

"""**minibatch_size** - размер мини-пакета - это количество записей

**learning_rate** - скорость обучения.
"""

train_loader = data_utils.DataLoader(X_train, batch_size=minibatch_size, shuffle=True)

test_loader = data_utils.DataLoader(X_test, batch_size=1, shuffle=False)

criterion = nn.MSELoss()
optimizer = torch.optim.Adam(
model.parameters(), lr=learning_rate, weight_decay=10e-05)

history = {}
history['train_loss'] = []
history['test_loss'] = []

for epoch in range(num_epochs):
    h = np.array([])
    for data in train_loader:
        output = model(data)
        loss = criterion(output, data)
        h = np.append(h, loss.item())
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()
    mean_loss = np.mean(h)
    print('epoch [{}/{}], loss:{:.4f}'.format(epoch + 1, num_epochs, mean_loss))
    history['train_loss'].append(mean_loss)
torch.save(model.state_dict(), './diamonds_autoencoder_model.pth')

plt.plot(history['train_loss'])
plt.title('model loss')
plt.ylabel('loss')
plt.xlabel('epoch')
plt.axis([0,100,0.69,0.80])
plt.show()

"""## Оценка модели"""

pred_losses = {'pred_loss' : []}
model.eval()
with torch.no_grad():
    for data in test_loader:
        inputs = data
        outputs = model(inputs)
        loss = criterion(outputs, inputs).data.item()
        pred_losses['pred_loss'].append(loss)
reconstructionErrorDF = pd.DataFrame(pred_losses)
reconstructionErrorDF['Class'] = y_test

reconstructionErrorDF.describe()

reconstructionErrorDF.describe()

