"""Здесь мы имеем прямо противоположную ситуацию. По мере увеличения ошибки реконструкции recall (полнота) уменьшается.

## Используем модель для того, чтобы сделать предсказание

Чтобы предсказать, относится ли новый бриллиант к редким дорогим объектам, будем использовать ошибку реконструкции. Если ошибка превышает выбранный порог, считаем объект аномалией.
"""

threshold = reconstructionErrorDF[reconstructionErrorDF['Class'] == 0]['pred_loss'].quantile(0.95)

